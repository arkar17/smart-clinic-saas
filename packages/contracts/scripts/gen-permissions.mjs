// Compiles docs/baseline-v1.1/PERMISSION_MATRIX_v1.1.csv into src/permissions.ts (Arch 7.3).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const csvPath = resolve(here, '../../../docs/baseline-v1.1/PERMISSION_MATRIX_v1.1.csv');

export function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

export function compileMatrix(text) {
  const [header, ...rows] = parseCsv(text);
  const col = (name) => header.indexOf(name);
  const out = {};
  for (const r of rows) {
    out[r[col('capability_id')]] = {
      PLATFORM_ADMIN: r[col('platform_admin')],
      CLINIC_ADMIN: r[col('clinic_admin')],
      RECEPTIONIST: r[col('receptionist')],
      DOCTOR: r[col('doctor')],
      PUBLIC_PATIENT: r[col('public_patient')],
    };
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const matrix = compileMatrix(readFileSync(csvPath, 'utf8'));
  const body = `// GENERATED by scripts/gen-permissions.mjs from PERMISSION_MATRIX_v1.1.csv. Do not edit by hand.
export const PERMISSION_MATRIX = ${JSON.stringify(matrix, null, 2)} as const;
`;
  writeFileSync(resolve(here, '../src/permissions.generated.ts'), body);
  console.log(`Compiled ${Object.keys(matrix).length} capabilities.`);
}
